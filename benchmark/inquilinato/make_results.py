"""Regenerates RESULTS.md from the committed runs. No model calls.

    python benchmark/inquilinato/make_results.py
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from lastro.dataset import load_responses, load_samples, load_sources  # noqa: E402
from lastro.report import compare_to_markdown  # noqa: E402
from lastro.runner import evaluate  # noqa: E402

HERE = Path(__file__).parent
ORDER = ["grounded", "always-answer", "no-retrieval", "parametric"]

PREAMBLE = """# Benchmark results — Lei do Inquilinato

32 questions over Lei 8.245/1991. Generated by `make_results.py` from the run files
in `runs/`; scoring makes no model calls, so these numbers reproduce exactly.

All variants use `gemini-2.5-flash` at `temperature=0` with `top_k=5` retrieval.
Each removes one defence from the `grounded` configuration:

| Variant | Retrieval | Refusal instruction |
| --- | :---: | :---: |
| `grounded` | yes | yes |
| `always-answer` | yes | no |
| `no-retrieval` | no | yes |
| `parametric` | no | no |
"""


def main() -> int:
    samples = load_samples(HERE / "samples.yaml")
    sources = load_sources(HERE / "sources.yaml")

    evaluations = []
    for name in ORDER:
        path = HERE / "runs" / f"{name}.yaml"
        if not path.exists():
            continue
        evaluations.append(evaluate(samples, load_responses(path), sources, suite=name))

    if not evaluations:
        print("no runs found")
        return 1

    parts = [PREAMBLE, "", "## Metrics", "", compare_to_markdown(evaluations), ""]
    parts.append(_read_notes())

    (HERE / "RESULTS.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote RESULTS.md from {len(evaluations)} run(s)")
    return 0


def _read_notes() -> str:
    notes = HERE / "NOTES.md"
    return notes.read_text(encoding="utf-8") if notes.exists() else ""


if __name__ == "__main__":
    raise SystemExit(main())
