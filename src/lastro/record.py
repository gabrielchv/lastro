"""Recording system outputs to a scoreable responses file.

Kept separate from scoring on purpose. Recording calls a live system and costs
money; scoring reads a file and is free, deterministic and safe to run in CI on
every push. Collapsing the two would make the benchmark unrunnable as a quality
gate, which is the main thing it is for.

The library itself never imports a model client. A system under test is anything
matching `SystemUnderTest`, so the provider dependency stays in the adapter.
"""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

import yaml

from lastro.types import Response, Sample


class SystemUnderTest(Protocol):
    """Anything that answers a benchmark question.

    Implementations live next to the system being measured, not here.
    """

    name: str

    def answer(self, sample: Sample) -> Response:  # pragma: no cover - protocol
        ...


def record(
    system: SystemUnderTest,
    samples: list[Sample],
    destination: Path,
    on_progress=None,
) -> list[Response]:
    """Run every sample through `system` and write the responses to `destination`."""
    responses = []
    for index, sample in enumerate(samples, start=1):
        response = system.answer(sample)
        responses.append(response)
        if on_progress:
            on_progress(index, len(samples), sample, response)
    write_responses(responses, destination, system_name=getattr(system, "name", ""))
    return responses


def write_responses(responses: list[Response], destination: Path, system_name: str = "") -> None:
    payload = [
        {
            "sample_id": response.sample_id,
            "refused": response.refused,
            "answer": response.answer,
            "retrieved_source_ids": list(response.retrieved_source_ids),
            "citations": [
                {"source_id": citation.source_id, "quote": citation.quote}
                for citation in response.citations
            ],
            "claims": list(response.claims),
        }
        for response in responses
    ]
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8") as handle:
        if system_name:
            handle.write(f"# Recorded from system: {system_name}\n")
        handle.write("# Generated by `lastro.record`. Scoring reads this file and makes no\n")
        handle.write("# model calls, so results are reproducible without an API key.\n")
        yaml.safe_dump(payload, handle, allow_unicode=True, sort_keys=False, width=100)


__all__ = ["SystemUnderTest", "record", "write_responses"]
